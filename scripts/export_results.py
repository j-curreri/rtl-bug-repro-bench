"""Export graded episodes to results/episodes.csv and results/SUMMARY.md.

    python3 -I scripts/export_results.py <bench-root> <out-dir>

Reads <bench-root>/eval/runs/<run>/<case>-<cond>/{result.json,transcript.jsonl}. An episode is
void when its transcript shows the subscription usage limit or a provider API error on an API
model; void episodes and the runs in EXCLUDE are kept in the CSV but left out of the tables.
"""
import csv
import json
import pathlib
import re
import sys
from collections import defaultdict

# qwen1: chat template rejected Claude Code's effort level, every request HTTP 500.
# pilot, glm-pilot: harness bring-up. opus1-retry: rerun of one classifier-stopped episode;
# the original stays as sample 1. glm-d6-*: one case only (the D6 hunt), not a tier sample.
# *-smoke: backend bring-up. nemotron-full-s1: unfinished run, on hold.
EXCLUDE = {"qwen1", "pilot", "glm-pilot", "opus1-retry", "codex-smoke", "gemini-smoke", "gemini2-smoke",
           "nemotron-full-s1"}
EXCLUDE_PREFIX = ("glm-d6-",)
# These and qwen120-* runs use a 120-turn cap; every other run uses the 60-turn default
# (result.json does not record the cap).
TURN_CAP_120 = {"qwen-turns120"}
# Claude Code session/weekly limit or API error; Codex usage limit; Antigravity quota.
VOID_RE = re.compile(r'hit your (session|weekly|usage) limit|"api_error_status":[0-9]|Individual quota reached')
MODELS = {"claude-opus-5-5": "Opus 5.5", "claude-sonnet-5-5": "Sonnet 5.5",
          "GLM-5.3-Flash-FTW": "GLM 5.3 Flash", "qwen38-27b": "Qwen3.8-27B",
          "granite-4.2-8b": "Granite 4.2 8B", "claude-haiku-5-5": "Haiku 5.5",
          "gpt-6.1-sol": "GPT-6.1 Sol", "gpt-6-luna": "GPT-6 Luna", "gpt-6-astra": "GPT-6 Astra",
          "gemini-3.8-flash-high": "Gemini 3.8 Flash", "gemini-4-argon-high": "Gemini 4 Argon",
          "claude-opus-5-5-high": "Opus 5.5 (Antigravity)"}
FIELDS = ["run", "case", "anon_id", "model", "backend", "tier", "condition", "reproduced",
          "fixed", "buggy", "grade_error", "turns", "duration_s", "cost_usd", "sandbox_flags",
          "agent_status", "void", "excluded"]


def outcome(g, side):
    v = g.get(side)
    return v.get("outcome") if isinstance(v, dict) else None


def episodes(root):
    for f in sorted(root.glob("eval/runs/*/*/result.json")):
        run = f.parent.parent.name
        if "interrupted" in run:
            continue
        d = json.loads(f.read_text())
        g = d.get("grade") or {}
        t = f.parent / "transcript.jsonl"
        api = d.get("backend") in (None, "claude", "codex", "gemini")
        void = api and t.exists() and bool(VOID_RE.search(t.read_text(errors="ignore")))
        model = MODELS.get(d.get("model"), d.get("model"))
        if run in TURN_CAP_120 or run.startswith("qwen120-"):
            model += " (120-turn cap)"
        if d.get("backend") == "codex" and d.get("effort") == "xhigh":
            model += " (effort xhigh)"
        yield {"run": run, "case": d["case"], "anon_id": d.get("anon_id"),
               "model": model, "backend": d.get("backend") or "claude",
               "tier": d.get("tier", "full"), "condition": d.get("condition"),
               "reproduced": int(bool(g.get("valid"))), "fixed": outcome(g, "fixed"),
               "buggy": outcome(g, "buggy"), "grade_error": g.get("error"),
               "turns": d.get("num_turns"), "duration_s": d.get("duration_s"),
               "cost_usd": d.get("cost_usd"), "sandbox_flags": len(d.get("leak_hits") or []),
               "agent_status": d.get("agent_status"), "void": int(void), "excluded": int(run in EXCLUDE or run.startswith(EXCLUDE_PREFIX))}


def main():
    root, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    rows = list(episodes(root))
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "episodes.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, FIELDS)
        w.writeheader()
        w.writerows(rows)

    scored = [r for r in rows if not r["void"] and not r["excluded"]]
    cells = defaultdict(lambda: defaultdict(lambda: [0, 0]))  # (model, tier, cond) -> run -> [ok, n]
    for r in scored:
        c = cells[(r["model"], r["tier"], r["condition"])][r["run"]]
        c[0] += r["reproduced"]
        c[1] += 1
    lines = ["# Results summary", "",
             "Bugs reproduced (test passes on the fixed core, does not pass on the buggy core).",
             "Generated by `scripts/export_results.py`; void and excluded episodes left out.", "",
             "| Model | Report tier | Condition | Per run | Total |", "| --- | --- | --- | --- | --- |"]
    for (model, tier, cond), runs in sorted(cells.items()):
        per = ", ".join(f"{ok}/{n} ({run})" for run, (ok, n) in sorted(runs.items()))
        ok, n = sum(v[0] for v in runs.values()), sum(v[1] for v in runs.values())
        lines.append(f"| {model} | {tier} | {cond} | {per} | {ok}/{n} ({100 * ok / n:.0f}%) |")
    (out / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} episodes, {len(scored)} scored -> {out}")


if __name__ == "__main__":
    main()
